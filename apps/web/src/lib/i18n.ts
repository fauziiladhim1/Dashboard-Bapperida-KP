export const DICT: Record<Lang, Record<Key, string>> = { id, en };

type T = (key: Key) => string;

/** "menambah fitur #12" / "created feature #12"; aksi/entitas tak dikenal ditampilkan apa adanya. */
export const auditText = (t: T, a: { action: string; entity: string; entityId: string | null }): string => {
  const known = (k: string) => (k in id ? t(k as Key) : null);
  return [known(`act.${a.action}`) ?? a.action, known(`ent.${a.entity}`) ?? a.entity, a.entityId ? `#${a.entityId}` : ''].filter(Boolean).join(' ');
};
